// Helper functions for easy consumption across components
export function getSubjectConstellation(subjectSlug: string): SubjectConstellationMeta | undefined {
  return subjectConstellations.find((s) => s.subjectSlug === subjectSlug);
}

export function getAllConstellationStars(): ConstellationStarNode[] {
  return subjectConstellations.flatMap((s) => s.stars);
}

export function findStarByTopic(subjectSlug: string, topicSlug: string): ConstellationStarNode | undefined {
  const subject = getSubjectConstellation(subjectSlug);
  return subject?.stars.find((s) => s.topicSlug === topicSlug);
}
